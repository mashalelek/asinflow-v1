//       The submit-time check. `reuse_ok` fired when the submitted TTL
//       matched the registered one and meant "same product, different ASIN
//       — proceed sharing the NNN". It was also a (brand, TTL) -> NNN
//       decision, which §18 now forbids outright: TTL is a derived hint,
//       never a key.
